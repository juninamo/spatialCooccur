# ---- Segmentation-free analysis of transcript coordinates (experimental) ----
#
# Transcripts of each gene are treated as a log-Gaussian Cox process (LGCP).
# The log-intensity is a linear combination of a shared "cell density" field
# and K spatial factors, each a Gaussian process approximated with random
# Fourier features (RFF; Rahimi & Recht 2008), following the random-feature
# latent variable model of Gundersen, Zhang & Engelhardt (AISTATS 2021) with
# the spatial coordinates as the (observed) inputs.
#
# Co-localization of two gene sets is summarized by the LGCP cross pair
# correlation g_AB(r), available in closed form from the fitted model and
# estimable model-free from binned counts (pcf_cross()).

# ---- Simulation -------------------------------------------------------------

# Internal: stationary Gaussian random field with an RBF covariance
# exp(-h^2 / (2 ell^2)) on an nx x ny grid (spacing delta), unit variance,
# generated by FFT on a padded torus.
.grf_fft <- function(nx, ny, delta, ell) {
  px <- stats::nextn(2 * nx + ceiling(4 * ell / delta))
  py <- stats::nextn(2 * ny + ceiling(4 * ell / delta))
  freq <- function(p) {
    k <- 0:(p - 1)
    ifelse(k < p / 2, k, k - p) * 2 * pi / (p * delta)
  }
  kx <- freq(px)
  ky <- freq(py)
  S <- exp(-0.5 * ell^2 * outer(kx^2, ky^2, "+"))
  noise <- matrix(stats::rnorm(px * py), px, py)
  raw <- Re(stats::fft(stats::fft(noise) * sqrt(S), inverse = TRUE))
  raw[seq_len(nx), seq_len(ny)] / sqrt(px * py * sum(S))
}

#' Simulate transcript coordinates from a multivariate log-Gaussian Cox process
#'
#' **Experimental.** Genes are organized in gene
#' sets (e.g. marker genes of cell types). The log-intensity of gene `j` in
#' set `S` at location `u` is
#' \deqn{\log\lambda_j(u) = \log\rho + \sigma_d d(u) + \sigma_s f_S(u) + c_S n(u),}
#' where `d` is a shared cellularity field, `f_S` a set-specific territory
#' field and `n` a "niche" field shared by the sets in `coloc`. All fields are
#' unit-variance Gaussian random fields with an RBF covariance, generated
#' exactly by FFT (not with random features). Transcripts are Poisson counts
#' on a `resolution` grid, placed uniformly within each grid cell.
#'
#' @param gene_sets Character vector of gene-set names.
#' @param n_genes_per_set Number of genes in each set.
#' @param size Side length of the square window (micrometres).
#' @param resolution Simulation grid spacing (micrometres).
#' @param rate Baseline transcripts per square micrometre per gene.
#' @param density_sd,density_lengthscale SD and length scale of the shared
#'   cellularity field.
#' @param set_sd,set_lengthscale SD and length scale of the set-specific fields.
#' @param coloc Named numeric vector of niche loadings, e.g.
#'   `c(A = 0.8, B = 0.8)` makes sets A and B co-localize; opposite signs make
#'   them segregate.
#' @param niche_lengthscale Length scale of the niche field.
#' @param seed Random seed.
#'
#' @return A data.frame with columns `x`, `y`, `gene`, `gene_set`, carrying an
#'   attribute `truth` (the generating parameters) usable with
#'   [lgcp_true_pair_correlation()].
#' @export
#' @examples
#' tx <- simulate_transcripts(size = 150, rate = 0.01, coloc = c(A = 1, B = 1))
#' head(tx)
#' table(tx$gene_set)
simulate_transcripts <- function(gene_sets = c("A", "B", "C"),
                                 n_genes_per_set = 5,
                                 size = 500,
                                 resolution = 2,
                                 rate = 0.02,
                                 density_sd = 0.5,
                                 density_lengthscale = 80,
                                 set_sd = 1,
                                 set_lengthscale = 15,
                                 coloc = c(A = 0.8, B = 0.8),
                                 niche_lengthscale = 20,
                                 seed = 1) {
  .seed_rng(seed)
  n <- ceiling(size / resolution)
  d <- .grf_fft(n, n, resolution, density_lengthscale)
  niche <- .grf_fft(n, n, resolution, niche_lengthscale)
  genes <- paste0(rep(gene_sets, each = n_genes_per_set), "_",
                  rep(seq_len(n_genes_per_set), length(gene_sets)))
  set_of <- rep(gene_sets, each = n_genes_per_set)
  cs <- stats::setNames(rep(0, length(gene_sets)), gene_sets)
  cs[intersect(names(coloc), gene_sets)] <- coloc[intersect(names(coloc), gene_sets)]
  cell_area <- resolution^2
  out <- vector("list", length(gene_sets))
  for (k in seq_along(gene_sets)) {
    f_s <- .grf_fft(n, n, resolution, set_lengthscale)
    loglam <- log(rate) + density_sd * d + set_sd * f_s + cs[[k]] * niche
    for (g in genes[set_of == gene_sets[k]]) {
      cnt <- stats::rpois(n * n, exp(loglam) * cell_area)
      idx <- rep(seq_len(n * n), cnt)
      ix <- (idx - 1) %% n
      iy <- (idx - 1) %/% n
      out[[length(out) + 1L]] <- data.frame(
        x = (ix + stats::runif(length(idx))) * resolution,
        y = (iy + stats::runif(length(idx))) * resolution,
        gene = g, gene_set = gene_sets[k], stringsAsFactors = FALSE
      )
    }
  }
  tx <- do.call(rbind, out)
  tx <- tx[tx$x < size & tx$y < size, , drop = FALSE]
  rownames(tx) <- NULL
  attr(tx, "truth") <- list(
    gene_sets = gene_sets, genes = genes, set_of = set_of, rate = rate,
    density_sd = density_sd, density_lengthscale = density_lengthscale,
    set_sd = set_sd, set_lengthscale = set_lengthscale,
    coloc = cs, niche_lengthscale = niche_lengthscale, size = size
  )
  tx
}

#' Simulate a multi-sample case-control transcript dataset
#'
#' **Experimental.** Calls
#' [simulate_transcripts()] for every sample, with a group-specific niche
#' loading for the co-localizing gene sets plus patient-level noise.
#'
#' @param n_samples_per_group Number of samples (patients) per group.
#' @param group_coloc Named list, one numeric niche loading per group, applied
#'   to every set in `coloc_sets`, e.g. `list(control = 0.3, case = 0.9)`.
#' @param coloc_sets Gene sets that share the niche field.
#' @param between_sample_sd SD of the per-sample noise on the niche loading.
#' @param seed Random seed.
#' @param ... Passed to [simulate_transcripts()].
#'
#' @return A data.frame as [simulate_transcripts()] with `sample_id`,
#'   `group` and `patient` columns.
#' @export
#' @examples
#' tx <- simulate_transcripts_groups(n_samples_per_group = 2, size = 120,
#'                                   rate = 0.01)
#' table(tx$sample_id, tx$group)
simulate_transcripts_groups <- function(n_samples_per_group = 4,
                                        group_coloc = list(control = 0.3, case = 0.9),
                                        coloc_sets = c("A", "B"),
                                        between_sample_sd = 0.1,
                                        seed = 1, ...) {
  .seed_rng(seed)
  groups <- names(group_coloc)
  if (is.null(groups) || any(groups == "")) stop("group_coloc must be a named list.")
  out <- list()
  for (g in groups) {
    for (s in seq_len(n_samples_per_group)) {
      sid <- paste0(g, "_", s)
      cval <- group_coloc[[g]] + stats::rnorm(1, sd = between_sample_sd)
      tx <- simulate_transcripts(coloc = stats::setNames(rep(cval, length(coloc_sets)), coloc_sets),
                                 seed = sample.int(.Machine$integer.max, 1), ...)
      tx$sample_id <- sid
      tx$group <- g
      tx$patient <- sid
      out[[sid]] <- tx
    }
  }
  res <- do.call(rbind, out)
  rownames(res) <- NULL
  res
}

#' True cross pair correlation of a simulated LGCP
#'
#' Closed-form cross pair correlation between two gene sets for data from
#' [simulate_transcripts()], for validating [pcf_cross()] and
#' [rff_pair_correlation()]. See [rff_pair_correlation()] for the three
#' types.
#'
#' @param truth The `truth` attribute of a [simulate_transcripts()] result.
#' @param set_a,set_b Gene-set names.
#' @param r Distances (micrometres).
#' @param type `"relative"`, `"full"` or `"composition"`.
#'
#' @return A data.frame with `r`, `g` and `log_g`.
#' @export
#' @examples
#' tx <- simulate_transcripts(size = 100, rate = 0.01)
#' lgcp_true_pair_correlation(attr(tx, "truth"), "A", "B", r = c(5, 10, 20))
lgcp_true_pair_correlation <- function(truth, set_a, set_b, r,
                                       type = c("relative", "full", "composition")) {
  type <- match.arg(type)
  k <- function(ell) exp(-r^2 / (2 * ell^2))
  sets <- truth$gene_sets
  cs <- truth$coloc
  # set-level log-intensity cross-covariance (genes within a set are identical)
  Cset <- function(a, b, density = TRUE) {
    C <- cs[[a]] * cs[[b]] * k(truth$niche_lengthscale)
    if (identical(a, b)) C <- C + truth$set_sd^2 * k(truth$set_lengthscale)
    if (density) C <- C + truth$density_sd^2 * k(truth$density_lengthscale)
    C
  }
  if (type == "composition") {
    C <- Cset(set_a, set_b, density = FALSE)
    return(data.frame(r = r, g = exp(C), log_g = C))
  }
  g_ab <- exp(Cset(set_a, set_b))
  if (type == "full") return(data.frame(r = r, g = g_ab, log_g = log(g_ab)))
  # all transcripts: weight sets by their expected intensity
  w <- exp(0.5 * (truth$set_sd^2 + cs[sets]^2))
  w <- w * table(truth$set_of)[sets]
  w <- w / sum(w)
  g_tt <- 0
  for (a in sets) for (b in sets) g_tt <- g_tt + w[[a]] * w[[b]] * exp(Cset(a, b))
  g <- g_ab / g_tt
  data.frame(r = r, g = g, log_g = log(g))
}

